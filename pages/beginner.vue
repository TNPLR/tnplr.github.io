            <h3 id="inverted-minors">低花反序：弱的叫得多，強的叫得少</h3>
            <p>沒有四張高花而有低花支持時，本制度採反序低花。二線支持為邀請以上，三線支持則為較弱的牌。這個的制度設計是為了善用較足夠的叫牌空間，確認適不適合打3NT。不能套用「跳得愈高就愈強」的印象。</p>
