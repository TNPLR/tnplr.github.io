            <h3 id="stayman">Stayman：詢問四張高花</h3>
            <p>1NT－2!C 的 2!C 是問叫，不表示梅花。初學先在持四張高花、至少 8 點時使用。開叫者無四張高花答 2!D，有四張紅心答 2!H，只有四張黑桃則答 2!S；兩門都有時先答紅心。</p>
            <p>若找到配合，邀請牌加至三線高花，成局牌則叫四線；若未找到配合，邀請牌通常再叫 2NT，成局牌通常再叫 3NT。開叫者有兩門四張高花、先答紅心後，答叫者回到 NT，仍須留意答叫者可能有四張黑桃，可依其邀請或成局力量補叫黑桃。</p>
