            <p><b>直接 4M</b> 在本站主要是五張以上支持的阻塞性加叫。不能把所有有成局力量的支持牌，都直接跳到四線；強牌應保留空間，讓同伴判斷是否還有滿貫機會。本課先辨認這些叫品；Jacoby 2NT 與 Splinter 的後續留待進階。</p>
