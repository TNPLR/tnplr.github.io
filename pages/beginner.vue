            <h2 id="lesson-2">第二課：評估手牌與開叫</h2>
            <p><b>本課目標：</b>先辨認自己的力量與牌型，再依制度選擇開叫。</p>
            <h3 id="hand-evaluation">大牌點與牌型</h3>
            <p>A 算 4 點，K 算 3 點，Q 算 2 點，J 算 1 點，其餘不計，稱為大牌點（HCP）。每門花色共 10 點，全副牌共 40 點。初學先按大牌點計算，待找到配合，再逐步理解短門與長門的價值，不宜一開始便將各種加點混算。</p>
            <p>牌型如 4333、4432、5332，係將四門張數由多至少排列；本文以此三種為平均牌型。手牌逐門列示時，則固定按 !S、!H、!D、!C 的次序閱讀。所謂單張為一張，缺門為零張；有單張或缺門者，不屬上述平均牌型。</p>
            <h3 id="opening">開叫的判斷次序</h3>
            <p>「開叫」是指此前尚無人提出花色或 NT 叫品。敵人已開叫時，即須使用第七課的競叫條件，不得直接套用下表。本制度以 12 點作一般開叫門檻；12 點以上原則上應開叫。</p>
            <ol>
                <li><b>先看是否強牌：</b>22 點以上，或有 8.5 個贏墩以上的強牌，以 2!C 開叫。贏墩評估留待進階，初學可先由教師協助。</li>
                <li><b>再看是否 20–21 點平均牌：</b>開叫 2NT，此時可能有五張高花。</li>
                <li><b>其餘 12–21 點，有五張高花：</b>先考慮 1!H／1!S；兩門高花均達五張時，先叫較長者，同長先黑桃。</li>
                <li><b>沒有五張高花，且為平均牌：</b>15–17 點開叫 1NT；12–14 或 18–19 點先開低花，日後再叫以區別力量。</li>
                <li><b>其餘一般開叫牌：</b>以長門為原則選擇一線花色，惟高花至少五張、方塊至少四張；梅花在非平均牌時至少四張，平均牌時可能僅兩張。同長的低花可先方塊，惟不得違反最低張數。</li>
                <li><b>未滿 12 點：</b>初期先學 Pass。長門弱牌另有阻塞叫可用，並非所有不足 12 點的牌都永遠只能 Pass。</li>
            </ol>
