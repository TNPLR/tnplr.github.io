            <h2 id="lesson-6">第六課：競叫、防禦與實戰</h2>
            <p><b>本課目標：</b>對手參與後仍先辨認角色，再使用相應條件；打牌時則以雙方合作為念。</p>
            <h3 id="competition">開叫、蓋叫與技術性賭倍</h3>
            <p>敵方先開叫後，我方叫出自己的花色，稱為蓋叫。其目的除爭取合約，也可能指示首攻。以右手敵方開叫一線低花為例，CMBC 的基本一線花色蓋叫須五張以上、8 點以上；二線蓋叫負擔較大，不能原封不動沿用一線門檻。</p>
            <table class="defensive">
                <thead><tr><th scope="col">情境</th><th scope="col">基本判斷</th></tr></thead>
                <tbody>
                    <tr><td>(1!C)－1!S</td><td>五張以上黑桃、8 點以上；弱牌仍須考量牌組品質與身價。</td></tr>
                    <tr><td>(1!D)－2!C</td><td>11 點以上且六張以上梅花，或 13 點以上且五張以上梅花。</td></tr>
                    <tr><td>(1!D)－X</td><td>一般型為 12 點以上，對其餘三門各有至少三張支持，請同伴選花色；不表示持有長方塊。</td></tr>
                    <tr><td>(1!D)－1NT</td><td>通常 16–18 點、近似平均牌，且方塊有擋張；好的 15 點屬邊界評估。</td></tr>
                </tbody>
            </table>
            <p>擋張是指在該門具有足以阻止對手立即連取長串贏墩的配置，例如 A，或有保護的 K。1NT 蓋叫與 1NT 開叫的點力、擋張條件不同。技術性賭倍則表示請同伴選擇其他花色，並非「我想處罰對方」；17 點以上強牌另可先賭倍再描述，但有擋張的 17–18 點平均牌通常直接蓋叫 1NT。</p>
            <p>在 (1!D)－X－(Pass) 後，若輪到自己且無適合懲罰的特殊手牌，縱然 0 點也通常須選一門作答，以免將同伴的請求選擇誤作懲罰。初學練習先用最低線位叫出可選的較長花色，較強答叫留待後續。另一方面，同伴開叫後遇敵方蓋叫，答叫條件與迫叫性亦可能改變，應另查競叫表，不能逕套第三課。</p>
            <h3 id="preempts">阻塞叫與身價</h3>
            <p>不足一般開叫力量而有長門時，可用阻塞叫占去對手的叫牌空間。CMBC 的基本範圍約 6–9 點，力量通常集中於長門：二線方塊、紅心或黑桃通常六張；三線花色通常七張；四線通常八張。<b>2!C 是強牌，不能拿弱六張梅花比照開叫。</b></p>
            <p>阻塞並非只數張數就一定要叫，尚須看身價、牌組品質與可能倒墩。身價為事先指定的計分狀態，會提高成局獎分及倒約的代價；在有身價時，犧牲合約可能付出較高分數。因此本課先學辨認與估計，不以背熟阻塞表取代判斷。</p>
            <h3 id="defense">首攻與小歡迎</h3>
            <p>首攻前，先回想同伴是否叫過花色，敵方顯示何種牌型。連張牌組可考慮引出連張中的最大牌，例如 KQJ 中的 K；王牌合約有 A 的花色，依本站 CMBC 的入門首攻約定先攻 A，不宜由 A 下方引小牌。無王與王牌的首攻目的不盡相同，完整細節另見制度全文。</p>
            <p>首攻後，若有適合打態度信號的機會，本站使用「小歡迎」：在同伴引出非王牌花色時，小牌表示希望續攻，大牌表示較不希望續攻。大、小是相對於手中可負擔的牌而言；應先遵守跟牌義務，也不能為了表示不歡迎而犧牲必要的贏張。</p>
            <p>例如同伴引 A，夢家為小牌，自己持 Q82，且本墩無須以大牌爭取時，可跟 2 表示歡迎。這是提供資訊，不是命令；同伴仍應合併夢家與叫牌判斷。無法跟牌時的墊牌信號另有約定，本課不與跟牌態度信號混用。</p>
            <h3 id="lesson-6-practice">練習與課程總檢討</h3>
            <ol>
                <li><b>右手敵方 1!C，持 !S KQJ84　!H 73　!D A62　!C 943：</b>10 點、五張黑桃，可考慮 1!S 蓋叫。並非須有 12 點才能參與，但應查看身價及牌組品質。</li>
                <li><b>右手敵方 1!D，持 !S KJ84　!H AQ73　!D 6　!C K943：</b>13 點，方塊短，其餘三門均有支持，適合技術性賭倍。此叫請同伴選擇，並不表示自己有長方塊。</li>
                <li><b>右手敵方 1!D，持 !S AQ7　!H K84　!D KJ6　!C Q943：</b>15 點平均牌，不宜僅因符合 1NT 開叫範圍就自動蓋叫 1NT；本制通常須 16–18 點，這手邊界牌先交由教師引導評估。</li>
            </ol>
            <p>最後安排四至六副預備牌，至少涵蓋高花配合、無王成局、部分合約與技術性賭倍。各人輪流說明：「同伴已表示什麼、我方有無配合、力量約在何處、此叫能否被 Pass。」檢討宜依作決定當時已知的資訊進行；不能因事後看到四手牌，便要求當時必須知道尚未揭露的配置。</p>
            <p>打牌前，莊家提出贏墩或失墩計畫；防家則說明首攻理由。六課所求，在於能有次序地思考，並依約定與同伴溝通。至於一副牌的成敗，尚受分配與技巧影響，不能單憑是否履約判斷叫牌必然正誤。</p>
        </div>

