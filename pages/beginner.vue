                    <tr><td>一線高花</td><td>6 點以上，4 張以上，迫叫一圈。</td></tr>
                    <tr><td>1!C－1!D</td><td>6 點以上，通常 4 張以上方塊；弱牌有四張高花時先叫高花。</td></tr>
