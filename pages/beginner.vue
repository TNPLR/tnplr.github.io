            <h2 id="thinking">叫牌的思考方法</h2>
            <p>叫牌所要決定者，無非「打什麼」與「打多高」兩事。前者關乎王牌與牌型，後者關乎雙方力量。故每次輪到自己，均可依下列次序思考：</p>
            <p class="principle">聽同伴 → 找配合 → 算力量 → 選高度 → 查能不能停。</p>
            <ol>
                <li><b>聽同伴：</b>同伴至少有幾點、幾張？哪些事情已經說過，哪些仍不明？不能把同伴「可能有」的牌，當作「必定有」的牌。</li>
                <li><b>找配合：</b>我方是否已有一門合計八張以上的花色？尤其應留意高花，也就是紅心與黑桃。五張加三張、四張加四張，均可構成八張配合。</li>
                <li><b>算力量：</b>把自己的點力與同伴已表示的範圍合併考量。若同伴表示 12–14 點，應保留這個範圍，不宜逕自當作 14 點。</li>
                <li><b>選高度：</b>現有資訊足以停在部分合約、邀請成局，抑或已可確定成局？倘尚未找到合適的王牌，是否應先描述牌型？</li>
                <li><b>查能不能停：</b>前一叫是否迫叫？自己這一叫，同伴能否 Pass？力量足夠，卻因誤解迫叫而過早停止，是初學時尤其應避免的情形。</li>
            </ol>
            <p>例如同伴開叫 1!S，自己有三張黑桃，便已知有八張配合；惟同伴尚可能有 12–21 點，故「找到配合」並不表示「已知應叫幾線」。反之，同伴開叫 1!C，自己雖有三張梅花，也不能遽認已有配合，因其在平均牌時可能僅有兩張梅花。</p>
