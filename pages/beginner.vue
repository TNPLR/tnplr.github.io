            <h3 id="glossary">基本用語</h3>
            <dl data-glossary-definitions>
                <dt>高花／低花</dt><dd>高花為紅心、黑桃；低花為梅花、方塊。</dd>
                <dt>配合</dt><dd>雙方在同門具有足以作王牌的張數，入門通常以合計八張以上為目標。</dd>
                <dt>加叫／支持</dt><dd>提高同伴已叫花色的線位，表示對該門的支持；力量仍依具體叫序判斷。</dd>
                <dt>邀請／束叫</dt><dd>邀請請同伴依力量決定是否再上升；束叫則表示按目前資訊希望停在該合約。</dd>
                <dt>迫叫</dt><dd>依約定要求同伴續叫；須區分迫叫一圈、迫叫成局及迫叫至指定線位。</dd>
                <dt>擋張／進手張</dt><dd>擋張用以阻止敵方在某門立即連取贏墩；進手張用以取得引牌權，使出牌能回到所需的一手。</dd>
                <dt>身價</dt><dd>一副牌預先指定的計分狀態，影響獎分及罰分，不是手牌點力的高低。</dd>
            </dl>
