            <h2 id="lesson-6">第六課：再叫與停止的時機</h2>
            <p><b>本課目標：</b>把同伴每次提供的資訊合併閱讀，並明辨迫叫與邀請。</p>
            <h3 id="forcing">三種停止條件</h3>
            <table>
                <thead><tr><th scope="col">用語</th><th scope="col">意義</th><th scope="col">例子</th></tr></thead>
                <tbody>
                    <tr><td>不迫叫</td><td>同伴可以 Pass，但未必應當 Pass。</td><td>1NT－2NT 的邀請。</td></tr>
