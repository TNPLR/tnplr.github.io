            <h3 id="major-special-raises">先辨認的特殊支持叫</h3>
            <p><b>Jacoby 2NT</b> 表示四張以上高花支持、12 點以上，迫叫成局；不是平均牌的自然邀請。有適合的短門時，本站另有 Splinter 可用。</p>
