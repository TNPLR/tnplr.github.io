                    <tr><td>8–9 點，恰五張高花</td><td>2NT，邀請；開叫者依力量與是否有三張支持，選擇高花或 NT。</td></tr>
                    <tr><td>8–9 點，六張以上高花</td><td>三線同門高花，邀請，不迫叫。</td></tr>
                    <tr><td>成局力量，恰五張高花</td><td>通常 3NT，讓開叫者有三張支持時改打四線高花。</td></tr>
                    <tr><td>成局力量，六張以上高花</td><td>可叫四線同門高花；另有直接四線轉換的制度叫品，留待延伸。</td></tr>
