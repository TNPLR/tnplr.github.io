            <h2 id="lesson-3">第三課：高花開叫後的答叫</h2>
            <p><b>本課目標：</b>同伴開叫 1!H 或 1!S 後，能依支持張數與力量，選擇直接支持、迫叫 1NT 或新花答叫，並辨認何時可以停止。</p>
            <p>本課假設答叫者未曾 Pass，且敵方均不介入。下文以 M 代表同伴開叫的高花，例如 2M 即為 2!H 或 2!S。</p>
            <h3 id="major-response">先找配合，再看力量</h3>
            <p>同伴開叫 1!H／1!S，表示 12–21 點、至少五張該門高花。自己只要有三張支持，便已有至少八張配合。然而，找到配合，只解決了「可以打什麼」，尚未決定「應打多高」。答叫時仍須區分：力量有限、邀請成局，還是已足以迫叫成局。同樣三張支持，6 點、9 點與 13 點，處理方式並不相同。</p>
            <p>本課先以大牌點為基礎。之後更進階時，可以學習更精準的計算方法。</p>
