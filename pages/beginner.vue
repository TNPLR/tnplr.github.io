            <p>以 1!C－1!H 為例，開叫者有四張紅心，可支持紅心；沒有四張紅心而有四張黑桃，可再叫 1!S；沒有高花配合，則依牌型與力量，考慮 NT、重叫梅花或其他合適叫品。</p>
