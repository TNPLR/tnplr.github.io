            <h2 id="lesson-1">第一課：規則與合約</h2>
            <p><b>本課目標：</b>先能依規則完成打牌，再理解叫牌究竟在約定什麼。</p>
            <h3 id="play-rules">一副牌如何進行</h3>
            <p>四人分坐東、南、西、北，相對而坐者為同伴。全副五十二張牌平均分配，每人十三張。每一輪由一人引牌，其餘依順時針方向各出一張，四張合成一「墩」。手中尚有引牌花色時，必須跟出該花色；已無該花色時，方得墊去別門，或於王牌合約中出王牌。可以將吃，不表示必須將吃。</p>
            <p>同花色的大小依序為 A、K、Q、J、10，以下至 2。若本墩無王牌，以引牌花色中最大者得墩；若有人出王牌，則以最大王牌得墩。得墩者引出下一墩。無王合約沒有王牌，別門即使出了 A，也不能勝過引牌花色的牌。</p>
            <p>例如無王合約中，西家引出 !H7，北、東、南依次出 !H10、!HK、!SA，則由東家的 !HK 得墩。南家須在已無紅心時，始可出黑桃 A；該張 A 並不能因此取得本墩。若同樣的出牌發生於黑桃合約，且南家確已無紅心，則黑桃 A 為王牌，由南家得墩。</p>
            <h3 id="auction-rules">叫牌如何決定合約</h3>
            <p>由發牌者先叫，依順時針輪流。花色叫品的高低依序為 !C、!D、!H、!S、NT；每一新叫品均須高於先前最高的叫品，例如 1!S 之後可以叫 1NT 或 2!C，不能叫 1!H。線位自一至七，所承諾的墩數為線位加六。</p>
            <p>Pass 表示本輪不提出新的叫品，並非永久退出；只要叫牌尚未結束，之後仍可能輪到自己。有人提出花色或 NT 叫品後，連續三人 Pass，叫牌即告結束；若開頭四人均 Pass，則為全 Pass。賭倍（Double，X）可針對敵方目前尚未賭倍的合約叫品提出；再賭倍（Redouble，XX）由被賭倍一方提出，均會影響得失分。若有人另叫更高的花色或 NT，先前的賭倍即不沿用。</p>
            <p>最後叫出最高花色或 NT 叫品的一方承作合約；該方最先叫過最終合約花色或 NT 的人為莊家，其同伴為夢家。因此，最後叫出合約的人未必是莊家。莊家左手邊的防家先攻，首攻後夢家攤牌，往後由莊家決定自己與夢家的出牌；夢家並非另行作主的第二位莊家。</p>
            <h3 id="lesson-1-practice">課堂練習與解析</h3>
            <p>先以迷你橋牌練習：各人報出大牌點，由教師協助指定合約，不必先行完整叫牌。每副輪換莊家與防家。夢家攤下後，莊家先說「合約須取幾墩，目前看得到幾墩」，再開始出牌。</p>
            <ol>
                <li><b>南 1!H，北 2!H，南 4!H，其餘皆 Pass，誰是莊家？</b>南家最先叫紅心，故南為莊家、北為夢家、西家首攻；須取十墩。</li>
                <li><b>北 1NT，南 3NT，其餘皆 Pass，誰是莊家？</b>北家最先叫 NT，故由北承作，須取九墩。</li>
                <li><b>同伴引出 !C2，夢家出 !C5，自己有 !CAQ，應出哪張？</b>若無其他資訊，先出 Q 即足以超過夢家的牌，未必須出 A。實際仍須看前後出牌；重點在於大牌應相互合作，毋須一概以最大牌取墩。</li>
            </ol>
