            <h2 id="lesson-3">第三課：低花開叫後的答叫</h2>
            <p><b>本課目標：</b>理解答叫是在補充資訊；先找高花，再依力量選擇新花、支持或 NT。</p>
            <h3 id="minor-response">先找高花，不急著支持低花</h3>
            <p>同伴開叫 1!C／1!D 後，通常 6 點以上應答叫。若能在一線叫出四張以上高花，應優先考慮；尤其未滿迫叫成局力量時，即使方塊較長，也宜先叫四張高花。低花有支持而另有四張高花者，也先找高花，以免錯失四四配合。</p>
            <p>兩門高花均可答叫時，先長後短；同為四張，先紅心；同為五張以上，先黑桃。此與開叫須有五張高花的條件不同：<b>開叫高花要五張，低花開叫後一線答叫高花只要四張。</b></p>
