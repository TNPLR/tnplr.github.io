            <p>橋牌之趣，在於兩人各持一手未盡相同的牌，僅憑有限的叫品與出牌，逐步推知彼此的力量，合力完成一項共同的目標。初學之時，叫品繁多，難免有無從措手之感；惟制度雖有細節，其思考仍有脈絡可循。本文以 <NuxtLink to="/cmbc">CMBC 自然制</NuxtLink>為基礎，依七次社課的次序，先說明遊戲如何進行，再由開叫、答叫而至再叫與競叫，使讀者得以循序建立一套可以反覆運用的判斷方法。</p>
