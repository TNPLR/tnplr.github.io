            <h2 id="lesson-4">第四課：1NT 開叫的後續</h2>
            <p><b>本課目標：</b>利用開叫者已明示的 15–17 點與平均牌型，練習由答叫者規劃合約。</p>
            <h3 id="nt-strength">先定力量，再看高花</h3>
            <p>1NT 開叫的資訊較明確，答叫者應先將自己的牌分為三類：0–7 點通常停在部分合約；8–9 點邀請成局；10 點以上通常已有成局力量。15 點以上的強答叫可能另有滿貫前景，不在本課要求之內。下列範圍以一般大牌點手牌為基礎，特殊長門牌尚須另作評估。</p>
