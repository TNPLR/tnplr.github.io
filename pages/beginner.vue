            <p>例如同伴開叫 1!S，自己有三張黑桃、6 點，不能直接套用「有支持就叫 2!S」。本站將這類較弱的三張支持，先放入迫叫 1NT，再於下一輪回到黑桃。反之，有三張支持、10–11 點，也不能直接叫 3!S；直接三線支持保證四張以上。先經 1NT，再於適當叫序中跳至 3!S，才表示三張支持的邀請。</p>
            <p>表中的後續以開叫者作低限再叫為前提。若同伴已跳叫或表示強牌，須重新判斷，不能機械地照原定計畫回叫。入門以 8–9 點簡單支持、10–11 點邀請作基本分界，邊界牌仍須評估。五張以上支持的弱牌另可考慮下述阻塞性加叫，不能只按點力套表。</p>
            <h3 id="forcing-1nt">迫叫 1NT：未必平均，也未必沒有支持</h3>
            <p>高花開叫後，1NT 承接許多未達迫叫成局力量、又沒有更合適答叫的牌。入門先以約 6–11 點理解，其中可能包括：</p>
            <ul>
                <li>沒有支持，也沒有力量在二線叫新花。</li>
                <li>有三張支持，但僅 6–7 點。</li>
                <li>有三張支持、10–11 點，準備下一輪邀請。</li>
                <li>有自己的長門，但不符合其他直接答叫條件。</li>
            </ul>
            <p class="principle">迫叫 1NT 不保證平均牌，也不否認同伴的高花配合。</p>
            <p>開叫者不能 Pass，必要時可能再叫短低花。例如 <b>1!S－1NT－2!C－2!S</b>，1NT 迫叫一圈；2!C 可能只有三張，不能立即認定梅花是長門。答叫者再叫 2!S，可以是兩張黑桃、6–9 點，也可以是三張黑桃、6–7 點，通常不迫叫。「迫叫一圈」要求同伴再叫一次，並不表示之後每個叫品都迫叫。</p>
            <h3 id="major-new-suit">沒有支持時：先看能否在一線叫黑桃</h3>
            <p>同伴開叫 1!H，自己有四張以上黑桃、6 點以上，通常可以答 1!S，迫叫一圈。此叫沒有點力上限；強牌也可先由 1!S 開始。</p>
            <p>但同伴開叫 1!S 後，紅心已無法在一線叫出。此時答 2!H 是二蓋一，須有五張以上紅心及迫叫成局力量。例如有五張紅心、8 點，同伴開叫 1!S，通常先答 1NT，不能只因紅心長就答 2!H。</p>
            <h3 id="two-over-one">二蓋一：不跳叫的新花，迫叫成局</h3>
            <p>二蓋一是指同伴一線開叫後，自己在二線「不跳叫」地叫出新花。<b>12 點以上</b>是二蓋一的基本力量門檻。</p>
